"""Experiment 08 - aggregate every run into statistics, figures and RESULTS.md.

Statistics are over BUILDINGS (18 cases: 2 climates x 3 types x 3 buildings). For
scenario-sampling policies, each building's value is the mean over the available seeds
and the seed-to-seed spread is reported separately. Confidence intervals: percentile
bootstrap over buildings (10,000 resamples, fixed seed).

    python experiments/08_summarize.py            # uses MG_RESULTS_DIR or ./results
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "experiments"))
import matplotlib                                                    # noqa: E402
matplotlib.use("Agg")
import matplotlib.pyplot as plt                                      # noqa: E402

from mgdispatch.runner import results_root                           # noqa: E402

TEAL, RED, GREY, GOLD, PURPLE, BLUE = "#154f58", "#c0392b", "#7f8c8d", "#e0a526", "#8e44ad", "#2e86ab"
POLICY_ORDER = ["rule_based", "mpc_forecast", "mpc_quantile", "mpc_stochastic", "mpc_robust",
                "mpc_perfect", "perfect_foresight_lp"]
POLICY_NAMES = {"rule_based": "Rule-based", "mpc_forecast": "Deterministic MPC",
                "mpc_quantile": "Quantile MPC (q=0.9)", "mpc_stochastic": "Stochastic MPC",
                "mpc_robust": "Robust (min-max) MPC", "mpc_perfect": "MPC, perfect forecast",
                "perfect_foresight_lp": "Perfect foresight (bound)"}


def boot_ci(x, n=10000, seed=0, stat=np.mean):
    x = np.asarray(x, float)
    x = x[~np.isnan(x)]
    if len(x) < 2:
        return (np.nan, np.nan)
    rng = np.random.default_rng(seed)
    s = [stat(rng.choice(x, len(x))) for _ in range(n)]
    return tuple(np.percentile(s, [2.5, 97.5]))


def load_runs(root: Path, sub: str = "raw") -> pd.DataFrame:
    rows = []
    records = [json.loads(f.read_text()) for f in root.glob(f"0[2345]_*/{sub}/*/*.json")]
    if sub == "raw":                                   # packed results (pack_results.py)
        for f in root.glob("0[2345]_*/runs.jsonl"):
            records += [json.loads(l) for l in f.read_text().splitlines() if l.strip()]
    for r in records:
        spec = r["spec"]
        rows.append({
            "exp": r["experiment"], "building": r["building"], "site": r["site"], "type": r["type"],
            "policy": spec["policy"], "seed": spec.get("seed", 0),
            "k": spec.get("error_scale", 1.0), "guard": spec.get("guard", True),
            "size": spec.get("sizing", {}).get("bat_power_fraction", np.nan),
            "total": r["bill"]["total"], "demand": r["bill"]["demand"],
            "energy": r["bill"]["energy_import"] - r["bill"]["export_credit"],
            "battery_kwh": r["battery"]["energy_kwh"], "battery_kw": r["battery"]["power_kw"],
            "cycles": r["equivalent_cycles"], "guard_actions": r["guard_actions"],
            "fallbacks": r["solver_stats"].get("milp_fallbacks", 0),
            "solves": r["solver_stats"].get("solves", 0), "wall_s": r["wall_time_s"],
            "skill": r.get("forecast_skill"), "eval_start": r["eval_start_local"],
            "eval_end": r["eval_end_local"],
        })
    return pd.DataFrame(rows)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true")
    args = ap.parse_args()
    root = results_root()
    sub = "quick" if args.quick else "raw"
    out = root / "summary" / ("quick" if args.quick else "")
    out.mkdir(parents=True, exist_ok=True)
    df = load_runs(root, sub)
    if df.empty:
        raise SystemExit(f"No results under {root}/0*_*/{sub}/")
    df.to_csv(out / "all_runs.csv", index=False)
    md = ["# Results", "",
          f"Generated by `experiments/08_summarize.py` from {df.building.nunique()} buildings "
          f"and {len(df)} runs. Evaluation window: {df.eval_start.min()[:10]} to "
          f"{df.eval_end.max()[:16]} (local time, 15-min resolution). Costs are the "
          "dispatch-dependent part of the PG&E B-19 bill over that window (the fixed customer "
          "charge is excluded). Savings are relative to the same building with PV but "
          "**no battery**. CIs: 95 % bootstrap over buildings.", ""]

    base = df[(df.exp == "03_policies") & (df.policy == "no_battery")].set_index("building")["total"]
    summary = {"n_buildings": int(df.building.nunique())}

    # ------------------------------------------------ exp 03 + 04: policy comparison
    core = df[df.exp.isin(["03_policies", "04_uncertainty"]) & df.guard & (df.policy != "no_battery")]
    per_b = core.groupby(["policy", "building"])["total"].mean().unstack(0)
    per_b = per_b[[p for p in POLICY_ORDER if p in per_b.columns]]
    sav = per_b.rsub(base.reindex(per_b.index), axis=0)                 # $ saved
    sav_pct = 100 * sav.div(base.reindex(per_b.index), axis=0)
    pf = sav["perfect_foresight_lp"] if "perfect_foresight_lp" in sav else None
    rows = []
    for p in sav.columns:
        x = sav_pct[p].dropna()
        lo, hi = boot_ci(x)
        capture = (100 * sav[p] / pf).dropna() if pf is not None else pd.Series(dtype=float)
        rows.append({"policy": POLICY_NAMES[p], "n": len(x), "mean saving %": x.mean(),
                     "95% CI": f"[{lo:.1f}, {hi:.1f}]", "median %": x.median(),
                     "min %": x.min(), "buildings worse than no battery": int((x < 0).sum()),
                     "share of perfect-foresight saving %": capture.median()})
    tab = pd.DataFrame(rows)
    summary["policies"] = tab.to_dict(orient="records")
    md += ["## 1. Policy comparison (with real-time demand guard)", "",
           tab.to_markdown(index=False, floatfmt=".1f"), ""]

    # paired differences
    pairs = [("mpc_stochastic", "mpc_forecast"), ("mpc_quantile", "mpc_forecast"),
             ("mpc_robust", "mpc_stochastic"), ("mpc_forecast", "rule_based"),
             ("mpc_stochastic", "rule_based")]
    prow = []
    for a, b in pairs:
        if a in sav_pct and b in sav_pct:
            d = (sav_pct[a] - sav_pct[b]).dropna()
            lo, hi = boot_ci(d)
            prow.append({"A minus B (saving, % of bill)": f"{POLICY_NAMES[a]} - {POLICY_NAMES[b]}",
                         "mean": d.mean(), "95% CI": f"[{lo:.2f}, {hi:.2f}]",
                         "A better in": f"{int((d > 0).sum())}/{len(d)}"})
    if prow:
        md += ["Paired differences (same building):", "", pd.DataFrame(prow).to_markdown(
            index=False, floatfmt=".2f"), ""]
        summary["paired"] = prow

    # operational EVPI / VSS analogues ($ per building over the window)
    if {"mpc_forecast", "mpc_perfect"} <= set(per_b.columns):
        evpi = per_b["mpc_forecast"] - per_b["mpc_perfect"]
        summary["evpi_usd_mean"] = float(evpi.mean())
        md += [f"*Value of a perfect forecast inside MPC* (deterministic MPC cost minus "
               f"perfect-forecast MPC cost): mean ${evpi.mean():,.0f} per building, "
               f"{100 * (evpi / base.reindex(evpi.index)).mean():.1f} % of the no-battery bill."]
    if {"mpc_forecast", "mpc_stochastic"} <= set(per_b.columns):
        vss = per_b["mpc_forecast"] - per_b["mpc_stochastic"]
        summary["vss_usd_mean"] = float(vss.mean())
        md += [f"*Value of the stochastic solution* (deterministic minus stochastic MPC "
               f"cost): mean ${vss.mean():,.0f} per building "
               f"(positive in {int((vss > 0).sum())}/{vss.notna().sum()} buildings).", ""]

    # by building type
    if len(sav_pct):
        bt = sav_pct.join(df.drop_duplicates("building").set_index("building")[["type", "site"]])
        g = bt.groupby(["type"])[[c for c in sav_pct.columns]].mean()
        g.columns = [POLICY_NAMES[c] for c in g.columns]
        md += ["Mean saving % by building type:", "", g.to_markdown(floatfmt=".1f"), ""]
        g2 = bt.groupby(["site"])[[c for c in sav_pct.columns]].mean()
        g2.columns = [POLICY_NAMES[c] for c in g2.columns]
        md += ["Mean saving % by climate:", "", g2.to_markdown(floatfmt=".1f"), ""]

    # seed spread
    sd = core[core.policy.isin(["mpc_stochastic", "mpc_robust"])]
    if sd.seed.nunique() > 1:
        spread = sd.groupby(["policy", "building"])["total"].agg(lambda x: x.max() - x.min())
        rel = spread / base.reindex(spread.index.get_level_values(1)).to_numpy() * 100
        md += [f"Scenario-sampling seeds: max-min spread across {sd.seed.nunique()} seeds is "
               f"median {rel.median():.2f} %, max {rel.max():.2f} % of the no-battery bill.", ""]
        summary["seed_spread_pct_median"] = float(rel.median())

    # figure 1: savings by policy
    if len(sav_pct.columns):
        fig, ax = plt.subplots(figsize=(10, 5))
        cols = list(sav_pct.columns)
        colors = {"MediumOffice": TEAL, "RetailStandalone": RED, "Warehouse": GREY}
        types = df.drop_duplicates("building").set_index("building")["type"]
        for j, p in enumerate(cols):
            x = sav_pct[p].dropna()
            ax.boxplot(x, positions=[j], widths=0.5, showfliers=False,
                       medianprops=dict(color="k"))
            jit = np.random.default_rng(j).uniform(-0.15, 0.15, len(x))
            ax.scatter(j + jit, x, s=18, c=[colors[types[b]] for b in x.index], zorder=3)
        ax.axhline(0, color="k", lw=0.8)
        ax.set_xticks(range(len(cols)))
        ax.set_xticklabels([POLICY_NAMES[c] for c in cols], rotation=20, ha="right", fontsize=9)
        ax.set_ylabel("Bill saving vs no battery (%)")
        ax.set_title(f"Battery bill savings by dispatch policy ({sav_pct.shape[0]} buildings, PG&E B-19)")
        for t, c in colors.items():
            ax.scatter([], [], c=c, label=t)
        ax.legend(fontsize=8, loc="lower right")
        fig.tight_layout()
        fig.savefig(out / "fig_policy_savings.png", dpi=150)
        plt.close(fig)

    # ------------------------------------------------ exp 05: forecast value
    fv = df[((df.exp == "05_forecast_value") | ((df.exp == "03_policies") & (df.policy == "mpc_forecast")))
            & df.guard]
    if fv.k.nunique() > 1:
        piv = fv.pivot_table(index="building", columns="k", values="total")
        s_pct = 100 * piv.rsub(base.reindex(piv.index), axis=0).div(base.reindex(piv.index), axis=0)
        ks = sorted(piv.columns)
        m = s_pct[ks].mean()
        ci = [boot_ci(s_pct[k]) for k in ks]
        # $ per building per 10 % change of the forecast error, linear fit k in [0.5, 1.5]
        near = [k for k in ks if 0.5 <= k <= 1.5]
        slopes = []
        for b in piv.index:
            y = piv.loc[b, near].to_numpy()
            if np.all(np.isfinite(y)) and len(near) >= 2:
                slopes.append(np.polyfit(near, y, 1)[0] * 0.1)
        slopes = np.array(slopes)
        months = (pd.Timestamp(df.eval_end.max()[:10]) - pd.Timestamp(df.eval_start.min()[:10])).days / 30.44
        summary["forecast_value"] = {"k": ks, "mean_saving_pct": m.tolist(),
                                     "usd_per_10pct_error_per_building_window": float(np.mean(slopes)),
                                     "window_months": months}
        md += ["## 2. What is forecast accuracy worth?", "",
               "Deterministic MPC with forecast = actual + k x (baseline forecast error).", "",
               pd.DataFrame({"k": ks, "mean saving %": m.values,
                             "95% CI": [f"[{a:.1f}, {b:.1f}]" for a, b in ci],
                             "buildings worse than no battery": [(s_pct[k] < 0).sum() for k in ks]}
                            ).to_markdown(index=False, floatfmt=".2f"), "",
               f"Around today's forecast quality (k = 0.5 to 1.5), each 10 % reduction of the "
               f"forecast error is worth on average **${np.mean(slopes):,.0f} per building** over "
               f"the {months:.1f}-month window (median ${np.median(slopes):,.0f}; "
               f"about ${np.mean(slopes) * 12 / months:,.0f} per year).", ""]
        fig, ax = plt.subplots(figsize=(7, 4.5))
        for b in s_pct.index:
            ax.plot(ks, s_pct.loc[b, ks], color=GREY, alpha=0.3, lw=0.8)
        ax.plot(ks, m.values, "o-", color=TEAL, lw=2.5, label="Mean over buildings")
        ax.fill_between(ks, [c[0] for c in ci], [c[1] for c in ci], color=TEAL, alpha=0.2,
                        label="95 % CI of mean")
        if "mpc_quantile" in sav_pct:
            ax.axhline(sav_pct["mpc_quantile"].mean(), color=GOLD, ls="--", label="Quantile MPC (k = 1)")
        if "mpc_stochastic" in sav_pct:
            ax.axhline(sav_pct["mpc_stochastic"].mean(), color=PURPLE, ls=":", label="Stochastic MPC (k = 1)")
        ax.axhline(0, color="k", lw=0.8)
        ax.set_xlabel("Forecast error scale k (0 = perfect, 1 = baseline forecaster)")
        ax.set_ylabel("Bill saving vs no battery (%)")
        ax.set_title("Deterministic MPC: savings vs forecast error")
        ax.legend(fontsize=8)
        fig.tight_layout()
        fig.savefig(out / "fig_forecast_value.png", dpi=150)
        plt.close(fig)

    # forecast skill
    sk = df[(df.exp == "03_policies") & (df.policy == "mpc_forecast") & df.skill.notna()]
    if len(sk):
        skill = pd.DataFrame(list(sk.skill), index=sk.building)
        md += ["Baseline forecaster skill (nMAE = MAE / mean, evaluation window), mean over buildings:",
               "", skill.mean().to_frame("nMAE").T.to_markdown(index=False, floatfmt=".3f"), ""]
        summary["forecast_skill"] = skill.mean().to_dict()

    # ------------------------------------------------ exp 02: sizing
    sz = df[df.exp == "02_sizing"]
    if len(sz):
        sz = sz.assign(saving=base.reindex(sz.building).to_numpy() - sz.total)
        months = (pd.Timestamp(df.eval_end.max()[:10]) - pd.Timestamp(df.eval_start.min()[:10])).days / 30.44
        sz["annual_saving"] = sz.saving * 12 / months
        sz["usd_per_kwh_yr"] = sz.annual_saving / sz.battery_kwh
        sz["breakeven_capex_10y"] = 10 * sz.usd_per_kwh_yr
        g = sz.groupby("size")[["usd_per_kwh_yr", "breakeven_capex_10y"]].median()
        g["mean saving %"] = sz.assign(p=100 * sz.saving / base.reindex(sz.building).to_numpy()).groupby("size").p.mean()
        # realistic factor: stochastic (or deterministic) MPC capture of perfect foresight at 0.25
        cap = None
        for p in ("mpc_stochastic", "mpc_quantile", "mpc_forecast"):
            if p in sav and pf is not None:
                cap = float((sav[p] / pf).median())
                cap_name = POLICY_NAMES[p]
                break
        md += ["## 3. Battery sizing (perfect-foresight upper bound, 2-hour battery)", "",
               "Annualised by 12 / window months. Break-even capex = installed cost per kWh at "
               "which the (upper-bound) savings repay the battery in 10 years, ignoring "
               "discounting, incentives and degradation of capacity.", "",
               g.reset_index().assign(size=lambda d: d["size"].map("{:.0%}".format)).rename(
                   columns={"size": "power / annual peak", "usd_per_kwh_yr": "$ per kWh-year",
                            "breakeven_capex_10y": "break-even capex, 10-yr ($/kWh)"}).to_markdown(
                   index=False, floatfmt=".1f"), ""]
        if cap is not None:
            md += [f"With a realistic controller ({cap_name}) capturing a median {100 * cap:.0f} % "
                   f"of the perfect-foresight saving at the 25 % size, the corresponding break-even "
                   f"capex is about ${g.loc[0.25, 'breakeven_capex_10y'] * cap:,.0f}/kWh.", ""]
            summary["realistic_capture"] = cap
        summary["sizing"] = g.reset_index().to_dict(orient="records")
        fig, ax = plt.subplots(1, 2, figsize=(11, 4.2))
        for t, c in {"MediumOffice": TEAL, "RetailStandalone": RED, "Warehouse": GREY}.items():
            d = sz[sz.type == t].assign(b0=lambda x: base.reindex(x.building).to_numpy())
            agg = d.groupby("size").agg(sav=("saving", "sum"), b0=("b0", "sum"),
                                        be=("breakeven_capex_10y", "median"))
            ax[0].plot(agg.index, 100 * agg.sav / agg.b0, "o-", color=c, label=t)
            ax[1].plot(agg.index, agg.be, "o-", color=c, label=t)
        ax[0].set_ylabel("Bill saving (%)")
        ax[1].set_ylabel("Break-even capex, 10-yr payback ($/kWh)")
        for a in ax:
            a.set_xlabel("Battery power / annual 15-min peak (2-h battery)")
            a.legend(fontsize=8)
        ax[0].set_title("Upper-bound savings grow with size...")
        ax[1].set_title("...but each extra kWh is worth less")
        fig.tight_layout()
        fig.savefig(out / "fig_sizing.png", dpi=150)
        plt.close(fig)

    # ------------------------------------------------ open-loop ablation
    ol = df[(df.exp == "04_uncertainty") & (~df.guard)]
    if len(ol):
        rows = []
        for p in [q for q in POLICY_ORDER if q in set(ol.policy)]:
            a = ol[ol.policy == p].groupby("building")["total"].mean()
            c = core[(core.policy == p) & (core.seed == 0)].groupby("building")["total"].mean()
            idx = a.index.intersection(c.index)
            sa = 100 * (base[idx] - a[idx]) / base[idx]
            sc = 100 * (base[idx] - c[idx]) / base[idx]
            rows.append({"policy": POLICY_NAMES[p], "n": len(idx),
                         "saving % open-loop": sa.mean(), "saving % with guard": sc.mean(),
                         "open-loop worse than no battery": f"{int((sa < 0).sum())}/{len(idx)}"})
        t = pd.DataFrame(rows)
        md += ["## 4. Ablation: executing MPC set-points open-loop (no real-time demand guard)", "",
               t.to_markdown(index=False, floatfmt=".1f"), ""]
        summary["openloop"] = rows

    # ------------------------------------------------ exp 06/07
    f6 = root / "06_milp_vs_lp" / ("quick" if args.quick else "") / "summary.json"
    if f6.exists():
        j = json.loads(f6.read_text())
        fc = j["fallback_counts"]
        t6 = pd.DataFrame([{"tariff variant": k, "windows": v["windows"],
                            "LP invalid (% of windows)": 100 * v["share_lp_invalid"],
                            "mean MILP-LP gap ($)": v["mean_gap_usd"],
                            "max simultaneous flow in LP (kW)": v["max_lp_violation_kw"],
                            "median LP / MILP time (ms)": f"{1000 * v['median_lp_s']:.0f} / {1000 * v['median_milp_s']:.0f}"}
                           for k, v in j["stress"].items()])
        md += ["## 5. When do the binary variables matter?", "",
               f"Across all {fc['solves']:,} MPC solves under B-19 the LP relaxation needed a MILP "
               f"fallback {fc['milp_fallbacks']} times. Stress tests on real MPC windows:", "",
               t6.to_markdown(index=False, floatfmt=".2f"), ""]
        summary["milp_vs_lp"] = j
    f7 = root / "07_solvers" / ("quick" if args.quick else "") / "summary.json"
    if f7.exists():
        j = json.loads(f7.read_text())
        t7 = pd.DataFrame([{"path": k, "median time per window (ms)": v.get("median_ms", np.nan),
                            "max |objective diff| vs direct HiGHS": v.get("max_abs_obj_diff_vs_direct", np.nan),
                            "note": v.get("error", "")} for k, v in j["solvers"].items()])
        t8 = pd.DataFrame(j["scaling"]).astype({"scenarios": int, "n_vars": int})
        md += ["## 6. Solvers", "", f"Same deterministic MPC windows ({j['building']}); "
               "MILP rows use a 1e-6 relative gap.", "", t7.to_markdown(index=False, floatfmt=".3g"), "",
               "Scaling of the stochastic LP (direct HiGHS):", "", t8.to_markdown(index=False, floatfmt=".1f"), ""]
        summary["solvers"] = j

    # compute cost
    md += ["## Compute", "", f"Total simulated wall time: {df.wall_s.sum() / 3600:.1f} CPU-hours; "
           f"MPC solves: {int(df.solves.sum()):,}; MILP fallbacks: {int(df.fallbacks.sum())}.", ""]
    (out / "RESULTS.md").write_text("\n".join(md))
    (out / "summary.json").write_text(json.dumps(summary, indent=2, default=float))
    print("\n".join(md[:60]))
    print(f"\nWrote {out/'RESULTS.md'}")


if __name__ == "__main__":
    main()
